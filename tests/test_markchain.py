from mdp.markchain import MarkChain, default_state_parser
import numpy as np
import random
from pathlib import Path

# Sample markdown for testing
SAMPLE_MARKDOWN = """# Test Document

This is a paragraph with some text that explains the concept.

## Installation

Follow these steps to install the package.

## Usage

Here's how to use the package.

## Troubleshooting

If you encounter issues, check the logs.

**Warning**: Do not modify system files directly.
"""

def test_generate_and_analyze_samples():
    """Test generating multiple samples from MarkChain and analyze them."""
    # Initialize and train the model
    chain = MarkChain()
    chain.train(SAMPLE_MARKDOWN)
    
    # Generate multiple samples with different seeds
    num_samples = 5
    samples = []
    
    # Use random seeds for different samples
    for i in range(num_samples):
        random.seed(i)
        np.random.seed(i)
        sample = chain.sample()
        samples.append(sample)
        assert isinstance(sample, str)
        assert len(sample) > 0
    
    # Save samples to the outputs directory for inspection
    output_dir = Path('tests/outputs')
    output_dir.mkdir(exist_ok=True)
    output_path = output_dir / 'markchain_samples.md'
    
    # Generate a markdown report with the samples and analysis
    with open(output_path, 'w') as f:
        f.write("# MarkChain Sample Generation Analysis\n\n")
        f.write("This file shows multiple samples generated by MarkChain from the same training data.\n\n")
        
        # Write the training data for reference
        f.write("## Training Data\n\n")
        f.write("```markdown\n")
        f.write(SAMPLE_MARKDOWN)
        f.write("\n```\n\n")
        
        # Write the samples and analysis
        f.write("## Generated Samples\n\n")
        
        for i, sample in enumerate(samples):
            f.write(f"### Sample {i+1} (seed={i})\n\n")
            f.write("```markdown\n")
            f.write(sample)
            f.write("\n```\n\n")
            
            # Basic analysis of the sample
            f.write("**Analysis**:\n\n")
            
            # Count states by type
            states = list(default_state_parser(sample))
            state_types = {}
            for state in states:
                state_type = "header" if state.startswith('#') else \
                            "list" if state.startswith('-') or state.startswith('*') else \
                            "code" if '```' in state else "paragraph"
                state_types[state_type] = state_types.get(state_type, 0) + 1
            
            f.write("State distribution:\n\n")
            for state_type, count in state_types.items():
                f.write(f"- {state_type}: {count}\n")
            
            # Identify if the sample has hierarchy
            headers = [s for s in states if s.startswith('#')]
            header_levels = [s.count('#') for s in headers]
            has_hierarchy = len(set(header_levels)) > 1
            
            f.write(f"\nHas heading hierarchy: {has_hierarchy}\n")
            
            # Check for lists and code blocks
            has_lists = any(s.startswith('-') or s.startswith('*') for s in states)
            has_code = any('```' in s for s in states)
            
            f.write(f"Contains lists: {has_lists}\n")
            f.write(f"Contains code blocks: {has_code}\n\n")
            
            # Calculate transition variety (how many different state transitions)
            transitions = []
            for j in range(len(states) - 1):
                transitions.append((states[j], states[j+1]))
            
            unique_transitions = len(set(transitions))
            total_transitions = len(transitions)
            
            f.write(f"Unique state transitions: {unique_transitions} out of {total_transitions} total\n\n")
            f.write("---\n\n")
        
        # Comparative analysis
        f.write("## Comparative Analysis\n\n")
        f.write("This section compares the variety across all generated samples.\n\n")
        
        # Calculate diversity of starting states
        starting_states = [list(default_state_parser(sample))[0] for sample in samples if list(default_state_parser(sample))]
        unique_starts = len(set(starting_states))
        
        f.write(f"Number of unique starting states: {unique_starts} out of {len(samples)}\n\n")
        
        # Calculate total unique states across all samples
        all_states = []
        for sample in samples:
            all_states.extend(list(default_state_parser(sample)))
        
        unique_states = len(set(all_states))
        
        f.write(f"Total unique states across all samples: {unique_states}\n")
        f.write(f"Total states generated: {len(all_states)}\n")
    
    # Test assertions
    assert len(samples) == num_samples
    assert all(isinstance(sample, str) for sample in samples)
    assert all(len(sample) > 0 for sample in samples) 